// Command ci5report reads `go test -json` of the CI-5 adversarial identity
// suite (internal/identitystack, TestCI5) on stdin, prints the test output as
// it streams, and writes the CI-5 report (PLAN-001 task T19): every case of
// the ADR-001 Annex B CI-5 catalogue (contracttest.CI5Cases), with the named
// subtests that prove it and their result. A subtest proves a case when its
// name carries the case's tag, "[CI-5.03] ...", which contracttest.Suite
// gives every tagged case.
//
// It exits 1 when a case has no subtest, or one of its subtests failed or was
// skipped; when any other test or subtest in the run failed or was skipped;
// or when the package failed (a build error, a panic).
//
// Usage: go test -tags identitystack -json -run '^TestCI5$' ./internal/identitystack | ci5report -out ci5-report.md
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/Navaladi2019/TicketingSystem/internal/identity/contracttest"
)

// event is one line of `go test -json` (test2json).
type event struct {
	Action  string
	Test    string
	Elapsed float64
	Output  string
}

// result is what the stream says about one test or subtest.
type result struct {
	Action  string // pass, fail, skip; "" if it never finished
	Elapsed float64
	Output  []string
}

type summary struct {
	tests      map[string]*result // by full name, subtests included
	order      []string
	packageBad bool
}

func read(r io.Reader, echo io.Writer) (*summary, error) {
	s := &summary{tests: map[string]*result{}}
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for sc.Scan() {
		var e event
		if err := json.Unmarshal(sc.Bytes(), &e); err != nil {
			// go test prints build errors as plain text.
			_, _ = fmt.Fprintln(echo, sc.Text())
			s.packageBad = true
			continue
		}
		if e.Output != "" {
			_, _ = io.WriteString(echo, e.Output)
		}
		if e.Test == "" {
			if e.Action == "fail" {
				s.packageBad = true
			}
			continue
		}
		res := s.tests[e.Test]
		if res == nil {
			res = &result{}
			s.tests[e.Test] = res
			s.order = append(s.order, e.Test)
		}
		switch e.Action {
		case "output":
			res.Output = append(res.Output, strings.TrimRight(e.Output, "\n"))
		case "pass", "fail", "skip":
			res.Action, res.Elapsed = e.Action, e.Elapsed
		}
	}
	return s, sc.Err()
}

// tagged are the tests whose last name element starts with the case's tag.
func (s *summary) tagged(id string) []string {
	var out []string
	for _, name := range s.order {
		last := name[strings.LastIndex(name, "/")+1:]
		if strings.HasPrefix(last, "["+id+"]") {
			out = append(out, name)
		}
	}
	return out
}

// report writes the markdown report and returns the problems that fail the run.
func report(w io.Writer, s *summary, now time.Time) []string {
	var problems []string
	p := func(format string, a ...any) { _, _ = fmt.Fprintf(w, format, a...) }
	p("# CI-5 report: adversarial identity suite\n\n")
	p("Generated by `make identity-attacks` (tools/ci/ci5report) on %s, against the compose Keycloak, ", now.UTC().Format(time.RFC3339))
	p("the production Keycloak adapter, and a platform database filled by one real group sync. ")
	p("ADR-001 Annex B CI-5; PLAN-001 task T19. The CI-5.06 negative fixture (the same tamper succeeding on Keycloak 26.1.2) ")
	p("runs in `make identity-attacks-fixture`.\n\n")
	p("| # | Case | Test | Result | Time |\n|---|---|---|---|---|\n")
	claimed := map[string]bool{}
	for _, c := range contracttest.CI5Cases() {
		names := s.tagged(c.ID)
		if len(names) == 0 {
			problems = append(problems, c.ID+": MISSING ("+c.Title+")")
			p("| %s | %s | none | MISSING | |\n", c.ID, c.Title)
			continue
		}
		for _, name := range names {
			claimed[name] = true
			res := s.tests[name]
			status := strings.ToUpper(res.Action)
			if status == "" {
				status = "DID NOT FINISH"
			}
			if status != "PASS" {
				problems = append(problems, fmt.Sprintf("%s: %s (%s)", name, status, c.ID))
			}
			p("| %s | %s | `%s` | %s | %.1fs |\n", c.ID, c.Title, name, status, res.Elapsed)
		}
	}
	var others []string
	for _, name := range s.order {
		if res := s.tests[name]; !claimed[name] && (res.Action == "fail" || res.Action == "skip" || res.Action == "") {
			others = append(others, name)
		}
	}
	sort.Strings(others)
	if len(others) > 0 {
		p("\nOther tests in the same run that did not pass:\n\n| Test | Result |\n|---|---|\n")
		for _, name := range others {
			status := strings.ToUpper(s.tests[name].Action)
			if status == "" {
				status = "DID NOT FINISH"
			}
			p("| `%s` | %s |\n", name, status)
			problems = append(problems, name+": "+status)
		}
	}
	if s.packageBad {
		problems = append(problems, "the package failed (build error or panic): see the test output")
	}
	if len(problems) == 0 {
		p("\n**All %d CI-5 cases pass.**\n", len(contracttest.CI5Cases()))
		return nil
	}
	p("\n**CI-5 FAILED:**\n\n")
	for _, pr := range problems {
		p("- %s\n", pr)
	}
	for _, name := range s.order {
		if res := s.tests[name]; res.Action == "fail" && !strings.Contains(name, "/") {
			p("\n<details><summary>%s output</summary>\n\n```\n%s\n```\n</details>\n", name, strings.Join(res.Output, "\n"))
		}
	}
	return problems
}

func main() {
	out := flag.String("out", "ci5-report.md", "report file")
	flag.Parse()
	s, err := read(os.Stdin, os.Stdout)
	if err != nil {
		fmt.Fprintln(os.Stderr, "ci5report:", err)
		os.Exit(2)
	}
	f, err := os.Create(*out)
	if err != nil {
		fmt.Fprintln(os.Stderr, "ci5report:", err)
		os.Exit(2)
	}
	problems := report(f, s, time.Now())
	if err := f.Close(); err != nil {
		fmt.Fprintln(os.Stderr, "ci5report:", err)
		os.Exit(2)
	}
	fmt.Println("ci5report: wrote", *out)
	for _, pr := range problems {
		fmt.Fprintln(os.Stderr, "ci5report:", pr)
	}
	if len(problems) > 0 {
		os.Exit(1)
	}
}
