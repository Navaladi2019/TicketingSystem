package main

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"go.yaml.in/yaml/v3"
)

const (
	header      = "# Code generated by tools/openapibundle from openapi.yaml and paths/*.yaml; DO NOT EDIT.\n"
	rootRefPref = "../openapi.yaml#"
	pathPrefix  = "/api/v1/"
)

// Bundle reads the root spec and every api/paths/<group>.yaml it references
// and returns one OpenAPI document. Path items are inlined; the components of
// a group file are merged into the root's; a `../openapi.yaml#/...` ref in a
// group file becomes `#/...`. A path in the wrong group file, a component name
// defined twice, a group file the root does not reference, a path in a group
// file the root does not reference, or a spec
// kin-openapi rejects is an error.
func Bundle(rootFile string) ([]byte, error) {
	root, err := readNode(rootFile)
	if err != nil {
		return nil, err
	}
	dir := filepath.Dir(rootFile)
	paths := get(root, "paths")
	if paths == nil || paths.Kind != yaml.MappingNode {
		return nil, errors.New("root has no paths mapping")
	}
	components := get(root, "components")
	if components == nil {
		components = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		root.Content = append(root.Content, scalar("components"), components)
	}

	files := map[string]*yaml.Node{}
	used := map[*yaml.Node]bool{} // path items some root entry points at
	for i := 0; i+1 < len(paths.Content); i += 2 {
		route, item := paths.Content[i].Value, paths.Content[i+1]
		ref := get(item, "$ref")
		if ref == nil || len(item.Content) != 2 {
			return nil, fmt.Errorf("path %s: the root keeps only a $ref to paths/<group>.yaml", route)
		}
		file, pointer, _ := strings.Cut(ref.Value, "#")
		group := strings.TrimSuffix(filepath.Base(file), ".yaml")
		if group == "" || file != "paths/"+group+".yaml" {
			return nil, fmt.Errorf("path %s: $ref %q is not paths/<group>.yaml#/pointer", route, ref.Value)
		}
		want := strings.SplitN(strings.TrimPrefix(route, pathPrefix), "/", 2)[0]
		if !strings.HasPrefix(route, pathPrefix) || want != group {
			return nil, fmt.Errorf("path %s belongs in paths/%s.yaml (group = first segment after /v1)", route, want)
		}
		doc, ok := files[file]
		if !ok {
			if doc, err = readNode(filepath.Join(dir, file)); err != nil {
				return nil, err
			}
			rewriteRefs(doc)
			files[file] = doc
		}
		target, err := resolve(doc, pointer)
		if err != nil {
			return nil, fmt.Errorf("path %s: %s: %w", route, file, err)
		}
		used[target] = true
		*item = *target
	}

	// Merge components in file-name order so the bundle is deterministic.
	names := make([]string, 0, len(files))
	for f := range files {
		names = append(names, f)
	}
	slices.Sort(names)
	for _, f := range names {
		if err := mergeComponents(components, get(files[f], "components"), f); err != nil {
			return nil, err
		}
	}
	if err := checkUnreferenced(dir, names); err != nil {
		return nil, err
	}
	for _, f := range names {
		if err := checkUnusedPaths(files[f], used, f); err != nil {
			return nil, err
		}
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, fmt.Errorf("encode bundle: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	spec, err := openapi3.NewLoader().LoadFromData(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("bundle does not load: %w", err)
	}
	if err := spec.Validate(context.Background()); err != nil {
		return nil, fmt.Errorf("bundle is not valid OpenAPI: %w", err)
	}
	return buf.Bytes(), nil
}

func readNode(path string) (*yaml.Node, error) {
	data, err := os.ReadFile(path) //nolint:gosec // a CLI reads the tree its caller names
	if err != nil {
		return nil, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: not a YAML mapping", path)
	}
	return doc.Content[0], nil
}

func scalar(v string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v} }

// get returns the value of key in mapping n, or nil.
func get(n *yaml.Node, key string) *yaml.Node {
	if n == nil {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// rewriteRefs turns `../openapi.yaml#/x` into `#/x` everywhere under n.
func rewriteRefs(n *yaml.Node) {
	if n.Kind == yaml.MappingNode {
		for i := 0; i+1 < len(n.Content); i += 2 {
			if v := n.Content[i+1]; n.Content[i].Value == "$ref" && v.Kind == yaml.ScalarNode {
				v.Value = strings.Replace(v.Value, rootRefPref, "#", 1)
			}
		}
	}
	for _, c := range n.Content {
		rewriteRefs(c)
	}
}

// resolve follows a JSON Pointer such as "/paths/~1api~1v1~1me" from doc.
func resolve(doc *yaml.Node, pointer string) (*yaml.Node, error) {
	n := doc
	for _, seg := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		seg = strings.ReplaceAll(strings.ReplaceAll(seg, "~1", "/"), "~0", "~")
		if n = get(n, seg); n == nil {
			return nil, fmt.Errorf("pointer %q does not resolve", pointer)
		}
	}
	if n.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("pointer %q is not a path item", pointer)
	}
	return n, nil
}

// mergeComponents adds each section's entries of from to into; a name defined
// twice (in the root or in another group file) is an error.
func mergeComponents(into, from *yaml.Node, file string) error {
	if from == nil {
		return nil
	}
	for i := 0; i+1 < len(from.Content); i += 2 {
		section, entries := from.Content[i].Value, from.Content[i+1]
		dst := get(into, section)
		if dst == nil {
			dst = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
			into.Content = append(into.Content, scalar(section), dst)
		}
		for j := 0; j+1 < len(entries.Content); j += 2 {
			name := entries.Content[j].Value
			if get(dst, name) != nil {
				return fmt.Errorf("%s: components.%s.%s is already defined", file, section, name)
			}
			dst.Content = append(dst.Content, entries.Content[j], entries.Content[j+1])
		}
	}
	return nil
}

// checkUnreferenced fails on a paths/*.yaml file the root does not reference,
// which would otherwise be silently left out of the contract.
func checkUnreferenced(dir string, used []string) error {
	all, err := filepath.Glob(filepath.Join(dir, "paths", "*.yaml"))
	if err != nil {
		return err
	}
	for _, f := range all {
		if rel := "paths/" + filepath.Base(f); !slices.Contains(used, rel) {
			return fmt.Errorf("%s is not referenced by the root openapi.yaml", rel)
		}
	}
	return nil
}

// checkUnusedPaths fails on a key under a group file's paths that no root
// paths entry $refs, which would otherwise be silently left out of the contract.
func checkUnusedPaths(doc *yaml.Node, used map[*yaml.Node]bool, file string) error {
	paths := get(doc, "paths")
	if paths == nil {
		return nil
	}
	for i := 0; i+1 < len(paths.Content); i += 2 {
		if !used[paths.Content[i+1]] {
			return fmt.Errorf("%s: path %s is not referenced by the root openapi.yaml", file, paths.Content[i].Value)
		}
	}
	return nil
}
