// Scanner is the sensitivity-scanner hook (HB-17, TICK-735). It is called with
// every generated artefact (HTML, search-index.js, schema.json, SVGs) and
// returns one finding per line to report. The default rule set is empty.
type Scanner func(rel string, data []byte) []string

// Git answers the two questions the check asks of the repository.
type Git interface {
	// IsAncestor reports whether sha is an ancestor of HEAD.
	IsAncestor(sha string) (bool, error)
}

var stampRe = regexp.MustCompile(`Content generated against main @ [^<]*`)
var stampShaRe = regexp.MustCompile(`Content generated against main @ ([0-9a-f]{7,40}) \(`)

// normalise removes the footer's sha and date, so a moving main never makes
// the committed pages stale (D-HB-3).
func normalise(data []byte) []byte {
	return stampRe.ReplaceAll(data, []byte("Content generated against main @ STAMP"))
}

// generatedFiles lists the files under docs/handbook that the build owns:
// everything but src/ and README.md.
func generatedFiles(base string) (map[string]bool, error) {
	out := map[string]bool{}
	err := filepath.WalkDir(base, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(base, p)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if rel == "src" {
				return filepath.SkipDir
			}
			return nil
		}
		if rel == "README.md" {
			return nil
		}
		out[rel] = true
		return nil
	})
	if os.IsNotExist(err) {
		return out, nil
	}
	return out, err
}

// Check rebuilds into memory and compares with the committed files, ignoring
// the footer stamp. It then checks the stamped sha is an ancestor of HEAD,
// that mermaid.min.js is the version pinned in docs/pins.md, and runs the
// scanner over every artefact. It returns one line per problem.
func Check(cfg Config, git Git) ([]string, error) {
	probe := cfg
	probe.Sha, probe.Date = "0000000", "1970-01-01"
	out, err := Build(probe)
	if err != nil {
		return nil, err
	}
	base := filepath.Join(cfg.Root, handbookDir)
	have, err := generatedFiles(base)
	if err != nil {
		return nil, err
	}
	var problems []string
	rels := make([]string, 0, len(out))
	for rel := range out {
		rels = append(rels, rel)
	}
	sort.Strings(rels)
	for _, rel := range rels {
		data, err := os.ReadFile(filepath.Join(base, filepath.FromSlash(rel))) //nolint:gosec // path built from generated names
		switch {
		case err != nil:
			problems = append(problems, fmt.Sprintf("%s/%s is missing; run `task handbook` and commit it", handbookDir, rel))
		case !bytes.Equal(normalise(data), normalise(out[rel])):
			problems = append(problems, fmt.Sprintf("%s/%s is stale; run `task handbook` and commit it", handbookDir, rel))
		}
		delete(have, rel)
	}
	var extra []string
	for rel := range have {
		extra = append(extra, rel)
	}
	sort.Strings(extra)
	for _, rel := range extra {
		problems = append(problems, fmt.Sprintf("%s/%s is not generated by the build; remove it", handbookDir, rel))
	}

	problems = append(problems, checkMermaidPin(cfg.Root)...)
	problems = append(problems, checkStamp(base, git)...)

	if cfg.Scanner != nil {
		for _, rel := range rels {
			for _, f := range cfg.Scanner(rel, out[rel]) {
				problems = append(problems, fmt.Sprintf("sensitivity scan: %s: %s", rel, f))
			}
		}
		schema := "src/database/schema.json"
		if data, err := os.ReadFile(filepath.Join(base, filepath.FromSlash(schema))); err == nil { //nolint:gosec // fixed repository path
			for _, f := range cfg.Scanner(schema, data) {
				problems = append(problems, fmt.Sprintf("sensitivity scan: %s: %s", schema, f))
			}
		}
		_ = filepath.WalkDir(filepath.Join(base, "src", "diagrams"), func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".svg") {
				return nil
			}
			if data, err := os.ReadFile(p); err == nil { //nolint:gosec // a diagram source found by the walk
				rel, _ := filepath.Rel(base, p)
				for _, f := range cfg.Scanner(filepath.ToSlash(rel), data) {
					problems = append(problems, fmt.Sprintf("sensitivity scan: %s: %s", filepath.ToSlash(rel), f))
				}
			}
			return nil
		})
	}
	return problems, nil
}

var pinRow = regexp.MustCompile("(?m)^\\| `mermaid`[^\n]*sha256 `([0-9a-f]{64})`")

func checkMermaidPin(root string) []string {
	pins, err := os.ReadFile(filepath.Join(root, "docs", "pins.md")) //nolint:gosec // fixed repository path
	if err != nil {
		return []string{"docs/pins.md: " + err.Error()}
	}
	m := pinRow.FindSubmatch(pins)
	if m == nil {
		return []string{"docs/pins.md has no `mermaid` row with a sha256"}
	}
	data, err := os.ReadFile(filepath.Join(root, handbookDir, "assets", "mermaid.min.js")) //nolint:gosec // fixed repository path
	if err != nil {
		return []string{"docs/handbook/assets/mermaid.min.js: " + err.Error()}
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != string(m[1]) {
		return []string{fmt.Sprintf("docs/handbook/assets/mermaid.min.js has sha256 %s, docs/pins.md pins %s", got, m[1])}
	}
	return nil
}

// checkStamp reads the sha stamped into the committed index.html and requires
// it to be an ancestor of HEAD (git merge-base --is-ancestor).
func checkStamp(base string, git Git) []string {
	data, err := os.ReadFile(filepath.Join(base, "index.html")) //nolint:gosec // fixed repository path
	if err != nil {
		return nil // already reported as missing
	}
	m := stampShaRe.FindSubmatch(data)
	if m == nil {
		return []string{"docs/handbook/index.html has no footer stamp"}
	}
	if git == nil {
		return nil
	}
	ok, err := git.IsAncestor(string(m[1]))
	switch {
	case err != nil:
		return []string{fmt.Sprintf("footer sha %s: %v", m[1], err)}
	case !ok:
		return []string{fmt.Sprintf("footer sha %s is not an ancestor of HEAD; rebuild with `task handbook` on a branch that contains it", m[1])}
	}
	return nil
}
