def _slug(name):
    return re.sub(r"[^A-Za-z0-9]+", "-", name.split(" ")[0]).strip("-")


def _bru_request(r, seq):
    out = [f"meta {{\n  name: {r['name']}\n  type: http\n  seq: {seq}\n}}\n"]
    kind = "json" if r["body"] is not None else "formUrlEncoded" if r["form"] is not None else "none"
    out.append(f"{r['method']} {{\n  url: {r['url']}\n  body: {kind}\n  auth: none\n}}\n")
    if r["headers"]:
        out.append("headers {\n" + "".join(f"  {k}: {v}\n" for k, v in r["headers"].items()) + "}\n")
    if r["body"] is not None:
        body = r["body"] if isinstance(r["body"], str) else json.dumps(r["body"], indent=2, ensure_ascii=False)
        out.append("body:json {\n" + _ind(body) + "\n}\n")
    if r["form"] is not None:
        out.append("body:form-urlencoded {\n" + "".join(f"  {k}: {v}\n" for k, v in r["form"]) + "}\n")
    if r["pre"]:
        out.append("script:pre-request {\n" + _ind(r["pre"]) + "\n}\n")
    if r["tests"]:
        out.append("tests {\n" + _ind(LOAD + "\n" + r["tests"]) + "\n}\n")
    if r["desc"]:
        out.append("docs {\n" + _ind(r["desc"]) + "\n}\n")
    return "\n".join(out)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


ERRORS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", "api", "errors.yaml")


def registered():
    """The problem codes api/errors.yaml registers, in its order. Fails when
    it parses none, or fewer than the file's `- code:` lines (a layout change
    that the pattern no longer matches would otherwise drop codes silently)."""
    with open(ERRORS, encoding="utf-8") as f:
        text = f.read()
    codes = re.findall(r"^  - code: ([a-z_]+)\s*$", text, re.M)
    lines = len(re.findall(r"^\s*- code:", text, re.M))
    if not codes or len(codes) < lines:
        raise SystemExit(f"collection.py: parsed {len(codes)} problem codes from api/errors.yaml, "
                         f"which has {lines} '- code:' lines; fix registered()")
    return codes


def write(out):
    """Writes the collection into out (the bruno/ folder), replacing it."""
    if os.path.isdir(out):
        shutil.rmtree(out)
    folders = build()
    _write(os.path.join(out, "bruno.json"), json.dumps({
        "version": "1", "name": "TicketingSystem acceptance and API suite", "type": "collection",
        "ignore": ["node_modules", ".git"]}, indent=2) + "\n")
    _write(os.path.join(out, "collection.bru"),
           "vars:pre-request {\n  seed_domain_a: tenant-a.test\n}\n\ndocs {\n" + _ind(COLLECTION_DOC) + "\n}\n")
    codes = "[" + ", ".join(f"'{c}'" for c in registered()) + "]"
    _write(os.path.join(out, "lib", "nava.js"), LIB.lstrip("\n").replace("__REGISTERED__", codes))
    _write(os.path.join(out, "environments", "local.bru"),
           "vars {\n" + "".join(f"  {k}: {v}\n" for k, v in ENV) + "}\n")
    for i, f in enumerate(folders, 1):
        _write(os.path.join(out, f["dir"], "folder.bru"),
               f"meta {{\n  name: {f['name']}\n  seq: {i}\n}}\n\ndocs {{\n" + _ind(f["desc"]) + "\n}\n")
        for j, r in enumerate(f["items"], 1):
            _write(os.path.join(out, f["dir"], _slug(r["name"]) + ".bru"), _bru_request(r, j))
    return folders


def requests(folders):
    """(folder, request name, method, url) for the coverage table."""
    for f in folders:
        for r in f["items"]:
            yield f["name"], r["name"], r["method"].upper(), r["url"]


# ------------------------------------------------------------------ coverage
STATUS_RE = re.compile(r"N\.problem\('[a-z_]+', (\d{3})\)|N\.status\((\d{3})\)|N\.(me)\(")


def asserted_status(r):
    """The HTTP statuses a request's tests assert (N.me is 200)."""
    out = set()
    for m in STATUS_RE.finditer(r["tests"]):
        out.add("200" if m.group(3) else m.group(1) or m.group(2))
    return out


def path_of(url):
    p = re.sub(r"^\{\{[a-z_]+\}\}", "", url).split("?")[0]
    return p


def operations(spec_text):
    """(operationId, METHOD, path, [statuses]) from api/openapi.bundled.yaml.
    The bundle is generated with a fixed layout, so this reads it by indent."""
    ops, path, op = [], None, None
    section = None
    for line in spec_text.splitlines():
        if line.startswith("components:"):
            break
        m = re.match(r"^  (/\S*):\s*$", line)
        if m:
            path = m.group(1)
            continue
        m = re.match(r"^    (get|put|post|delete|patch|head|options):\s*$", line)
        if m and path:
            op = {"method": m.group(1).upper(), "path": path, "id": None, "statuses": []}
            ops.append(op)
            section = None
            continue
        m = re.match(r"^      operationId:\s*(\S+)", line)
        if m and op:
            op["id"] = m.group(1)
        if re.match(r"^      responses:\s*$", line):
            section = "responses"
            continue
        if re.match(r"^      \S", line):
            section = None
        m = re.match(r'^        "?(\d{3})"?:\s*$', line)
        if m and op and section == "responses":
            op["statuses"].append(m.group(1))
    return ops


def _match(template, path):
    rx = "^" + re.sub(r"\\\{[^}]+\\\}", "[^/]+", re.escape(template)) + "$"
    return re.match(rx, path) is not None


def coverage(folders, spec_text, exempt):
    """For every operation and documented status: the requests that cover it,
    or the reason it is exempt. Raises SystemExit when one has neither."""
    rows, missing = [], []
    reqs = [(f, r) for f in folders for r in f["items"]]
    for op in operations(spec_text):
        hits = [(f, r) for f, r in reqs if r["method"].upper() == op["method"] and _match(op["path"], path_of(r["url"]))]
        if not hits:
            missing.append(f"{op['id']} ({op['method']} {op['path']}): no Bruno request")
        for st in op["statuses"]:
            by = [r["name"].split(" ")[0] for f, r in hits if st in asserted_status(r)]
            why = exempt.get(op["id"], {}).get(st)
            if not by and not why:
                missing.append(f"{op['id']} {st}: no Bruno request asserts it and no exemption in build/coverage-exempt.json")
            rows.append((op["id"], f"{op['method']} {op['path']}", st, ", ".join(by) if by else "", why or ""))
    if missing:
        raise SystemExit("Bruno coverage check failed:\n  " + "\n  ".join(missing))
    return rows
