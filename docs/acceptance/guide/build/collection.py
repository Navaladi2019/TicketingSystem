def _ind(text, n=2):
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in text.strip("\n").split("\n"))


def req(name, method, url, *, desc="", headers=None, body=None, form=None, tests="", pre="", auth=None):
    """auth: None (no Authorization), or a variable name holding a bearer token.
    tests and pre are JavaScript; tests get N (lib/nava.js) loaded."""
    h = {}
    if auth:
        h["Authorization"] = "Bearer {{%s}}" % auth
    h.update(headers or {})
    if body is not None:
        h["Content-Type"] = h.get("Content-Type", "application/json")
    return {"name": name, "method": method.lower(), "url": url, "desc": desc, "headers": h,
            "body": body, "form": form, "tests": tests.strip("\n"), "pre": pre.strip("\n")}


def token(name, user, pwd, store, *, client="nava-web", scope="openid", desc="", extra=""):
    """A Keycloak password-grant token request that keeps the access token."""
    return req(
        name, "POST", "{{keycloak_url}}/realms/{{realm}}/protocol/openid-connect/token",
        desc=desc or f"Signs in as `{{{{{user}}}}}` through Keycloak (client `{client}`, password grant) and keeps the access token in the runtime variable `{store}`.",
        form=[("grant_type", "password"), ("client_id", client), ("scope", scope),
              ("username", "{{%s}}" % user), ("password", "{{%s}}" % pwd)],
        tests=f"""
test('HTTP 200 from Keycloak', () => expect(res.getStatus()).to.eql(200));
const tok = N.json();
test('access token issued', () => expect(tok.access_token).to.be.a('string'));
bru.setVar('{store}', tok.access_token);
if (tok.id_token) bru.setVar('{store}_id', tok.id_token);
const c = N.jwt(tok.access_token);
bru.setVar('{store}_exp', String(c.exp));
test('issuer is the pinned realm URL', () => expect(c.iss).to.eql(N.url('{{{{keycloak_issuer_url}}}}/realms/{{{{realm}}}}')));
{extra}
""")


def problem_req(name, method, url, code, status, *, desc, auth=None, headers=None, body=None, extra="", pre=""):
    return req(name, method, url, desc=desc, auth=auth, headers=headers, body=body, pre=pre,
               tests=f"N.problem('{code}', {status});\n{extra}")


